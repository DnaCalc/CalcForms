"""Export or byte-check the reviewed W010 MSForms parity ledger."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from cli_trust import select_export_path, write_reviewed_artifact
from parity_ledger import (
    LedgerError,
    build_expected_ledger_manifest,
    build_ledger,
    canonical_json_bytes,
    load_json_strict,
    validate_committed_ledger,
)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[2],
    )
    parser.add_argument(
        "--output",
        type=Path,
        help=(
            "compatibility override; may only name the reviewed committed "
            "parity-ledger artifact (relative paths are repository-relative)"
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare canonical generated bytes without writing",
    )
    args = parser.parse_args()
    repo_root = args.repo_root.resolve()
    try:
        ledger = build_ledger(repo_root)
        strict_errors = validate_committed_ledger(repo_root, ledger)
        if strict_errors:
            raise LedgerError("; ".join(strict_errors))
        manifest = build_expected_ledger_manifest(ledger)
        output = select_export_path(
            repo_root, manifest.get("artifact_path"), args.output
        )
        canonical = canonical_json_bytes(ledger)
        if args.check:
            if not output.is_file():
                raise LedgerError(f"committed ledger is missing: {output}")
            loaded = load_json_strict(output)
            if output.read_bytes() != canonical or loaded != ledger:
                raise LedgerError("committed ledger differs from canonical regeneration")
            print(
                f"OK {output.relative_to(repo_root).as_posix()} "
                f"rows={ledger['summary']['rows']} sha256={ledger['canonical_sha256']}"
            )
            return 0
        output = write_reviewed_artifact(
            repo_root, manifest.get("artifact_path"), canonical
        )
        print(
            f"wrote {output.relative_to(repo_root).as_posix()} "
            f"rows={ledger['summary']['rows']} sha256={ledger['canonical_sha256']}"
        )
        return 0
    except (LedgerError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
