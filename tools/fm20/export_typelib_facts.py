#!/usr/bin/env python3
"""Generate or byte-check the pinned W010 FM20 fact artifacts."""

from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

import typelib_facts


REPO_ROOT = Path(__file__).resolve().parents[2]
EVIDENCE_DIR = (
    REPO_ROOT
    / "docs/evidence/W010_complete_msforms_object_model_parity/beads/oxforms-jbjp.2"
)
DEFAULT_FACTS = EVIDENCE_DIR / "fm20_typelib_facts.v1.json"
DEFAULT_COMPARISON = EVIDENCE_DIR / "w005_event_reconciliation.v1.json"
DEFAULT_PINS = Path(__file__).resolve().with_name("pinned_typelibs.v1.json")
DEFAULT_W005_PIN = Path(__file__).resolve().with_name("pinned_w005_baseline.v1.json")
DEFAULT_EXPECTED_CAPTURE = Path(__file__).resolve().with_name("expected_capture.v1.json")
DEFAULT_W005 = (
    REPO_ROOT
    / "docs/evidence/W005_input_interaction_model_exploration/fm20_typelib_w005_events.json"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--pins", type=Path, default=DEFAULT_PINS)
    parser.add_argument("--w005", type=Path, default=DEFAULT_W005)
    parser.add_argument("--w005-pin", type=Path, default=DEFAULT_W005_PIN)
    parser.add_argument(
        "--expected-capture", type=Path, default=DEFAULT_EXPECTED_CAPTURE
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_FACTS)
    parser.add_argument("--comparison", type=Path, default=DEFAULT_COMPARISON)
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare regenerated bytes with the committed artifacts",
    )
    return parser.parse_args()


def fail_on_errors(label: str, errors: list[str]) -> None:
    if errors:
        formatted = "\n".join(f"  - {error}" for error in errors)
        raise typelib_facts.FactError(f"{label} failed:\n{formatted}")


def replace_atomically(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent, prefix=f".{path.name}.", suffix=".tmp"
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(payload)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def compare_bytes(path: Path, expected: bytes) -> None:
    if not path.is_file():
        raise typelib_facts.FactError(f"Committed artifact is missing: {path}")
    actual = path.read_bytes()
    if actual != expected:
        raise typelib_facts.FactError(
            f"Regenerated bytes differ from committed artifact: {path}"
        )


def generate(
    source: Path,
    pins: dict,
    w005: dict,
    w005_pin: dict,
    expected_capture: dict,
    args: argparse.Namespace,
) -> tuple[dict, dict, bytes, bytes]:
    facts = typelib_facts.TypeLibExporter(source).export(
        [Path(__file__), Path(typelib_facts.__file__), args.pins]
    )
    fail_on_errors(
        "fact-pack validation",
        typelib_facts.validate_fact_pack(facts, require_sources=True),
    )
    fail_on_errors(
        "fact-pack pin reconciliation",
        typelib_facts.validate_fact_pack_against_pins(facts, pins),
    )
    comparison = typelib_facts.build_w005_comparison(
        facts,
        w005,
        w005_path=args.w005,
        w005_pin=w005_pin,
        w005_pin_path=args.w005_pin,
    )
    fail_on_errors(
        "W005 reconciliation",
        typelib_facts.validate_w005_comparison(
            comparison,
            facts,
            w005,
            w005_pin=w005_pin,
            w005_pin_path=args.w005_pin,
        ),
    )
    fail_on_errors(
        "reviewed capture pin",
        typelib_facts.validate_expected_capture(
            expected_capture, facts, comparison
        ),
    )
    return (
        facts,
        comparison,
        typelib_facts.canonical_json_bytes(facts),
        typelib_facts.canonical_json_bytes(comparison),
    )


def main() -> int:
    args = parse_args()
    pins = typelib_facts.load_json_strict(args.pins)
    w005_pin = typelib_facts.load_json_strict(args.w005_pin)
    expected_capture = typelib_facts.load_json_strict(args.expected_capture)
    fail_on_errors("pin manifest", typelib_facts.validate_pin_manifest(pins))
    fail_on_errors("live pinned inputs", typelib_facts.validate_live_pins(pins))
    root_pin = next(item for item in pins["libraries"] if item["role"] == "root")
    source = (args.source or Path(root_pin["path"])).resolve(strict=True)
    if source != Path(root_pin["path"]).resolve(strict=True):
        raise typelib_facts.FactError(
            f"Source {source} is not the independently pinned root {root_pin['path']}"
        )
    if sys.maxsize <= 2**32:
        raise typelib_facts.FactError("Pinned regeneration requires 64-bit Python")

    w005 = typelib_facts.load_json_strict(args.w005)
    fail_on_errors(
        "W005 baseline pin",
        typelib_facts.validate_w005_baseline_pin(
            w005_pin, w005, w005_path=args.w005
        ),
    )
    facts, comparison, fact_bytes, comparison_bytes = generate(
        source, pins, w005, w005_pin, expected_capture, args
    )
    if args.check:
        (
            _second_facts,
            _second_comparison,
            second_fact_bytes,
            second_comparison_bytes,
        ) = generate(source, pins, w005, w005_pin, expected_capture, args)
        if (fact_bytes, comparison_bytes) != (
            second_fact_bytes,
            second_comparison_bytes,
        ):
            raise typelib_facts.FactError(
                "Two clean in-process regenerations produced different bytes"
            )
        compare_bytes(args.output, fact_bytes)
        compare_bytes(args.comparison, comparison_bytes)
        action = "matched"
    else:
        # Both payloads are complete and validated before either target changes.
        replace_atomically(args.output, fact_bytes)
        replace_atomically(args.comparison, comparison_bytes)
        action = "wrote"
    print(
        f"{action} {facts['summary']['exported_type_view_count']} type views, "
        f"{facts['summary']['type_reference_count']} references, "
        f"{comparison['counts']['current_projection']['rows']} W005 rows"
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, KeyError, typelib_facts.FactError) as error:
        print(f"FM20 fact export failed: {error}", file=sys.stderr)
        raise SystemExit(1)
